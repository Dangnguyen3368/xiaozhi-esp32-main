"""Generates the Vietnamese voice alerts of the car mode (main/nav/nav_voice_data.cc).

Run: pip install edge-tts && python tools/nav_voice/gen.py
Needs ffmpeg. Each clip is Opus in an Ogg file (16 kHz mono, like the other sounds), embedded
as a byte array so no CMake EMBED_FILES change is needed.
"""

import asyncio
import os
import subprocess
import sys
import tempfile

import edge_tts

VOICE = "vi-VN-HoaiMyNeural"
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
OUT = os.path.join(ROOT, "main", "nav", "nav_voice_data.cc")

# C name -> words. Keep in sync with NavVoice in main/nav/nav_voice.h.
CLIPS = [
    ("camera", "Phía trước có camera giám sát, chú ý tốc độ."),
    ("overspeed", "Bạn đang chạy quá tốc độ."),
    ("jam", "Phía trước đang tắc đường."),
    ("gps_ok", "Đã bắt được tín hiệu GPS."),
    ("leave_early", "Đường hôm nay đông hơn mọi ngày, bạn nên đi sớm."),
    ("road_ok", "Đường đi hôm nay thông thoáng."),
    ("gps_module", "Đã kết nối GPS, đang tìm vệ tinh."),
]


async def make(name, text, tmp):
    mp3 = os.path.join(tmp, name + ".mp3")
    ogg = os.path.join(tmp, name + ".ogg")
    await edge_tts.Communicate(text, VOICE, rate="+5%").save(mp3)
    subprocess.run([
        "ffmpeg", "-y", "-loglevel", "error", "-i", mp3,
        "-af", "silenceremove=start_periods=1:start_threshold=-45dB,areverse,"
               "silenceremove=start_periods=1:start_threshold=-45dB,areverse,apad=pad_dur=0.1",
        "-c:a", "libopus", "-b:a", "16k", "-ac", "1", "-ar", "16000", "-frame_duration", "60", ogg,
    ], check=True)
    with open(ogg, "rb") as f:
        return f.read()


async def main():
    out = [
        "// Generated by tools/nav_voice/gen.py (Edge TTS, voice vi-VN-HoaiMyNeural). Do not edit.\n",
        '#include "nav_voice.h"\n\n#include <cstdint>\n\nnamespace nav_voice {\nnamespace {\n',
    ]
    names = []
    with tempfile.TemporaryDirectory() as tmp:
        for name, text in CLIPS:
            data = await make(name, text, tmp)
            names.append(name)
            print(f"{name}: {text} -> {len(data)} bytes")
            out.append(f"// {text}\nconst uint8_t k_{name}[] = {{")
            for i, b in enumerate(data):
                if i % 20 == 0:
                    out.append("\n    ")
                out.append(f"{b},")
            out.append("\n};\n\n")
    out.append("}  // namespace\n\nstd::string_view Clip(Id id) {\n    switch (id) {\n")
    for name in names:
        out.append(f"        case Id::k_{name}:\n"
                   f"            return {{reinterpret_cast<const char*>(k_{name}), sizeof(k_{name})}};\n")
    out.append("    }\n    return {};\n}\n\n}  // namespace nav_voice\n")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("".join(out))


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
