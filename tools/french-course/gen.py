#!/usr/bin/env python3
"""Generates main/french/french_lessons_data.cc from tools/french-course/lessons.py.

Run from the repository root:  python tools/french-course/gen.py
"""
import importlib.util
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "main" / "french" / "french_lessons_data.cc"

spec = importlib.util.spec_from_file_location("lessons", pathlib.Path(__file__).with_name("lessons.py"))
lessons = importlib.util.module_from_spec(spec)
spec.loader.exec_module(lessons)

# Characters the TFT can draw: ASCII, Latin-1 letters (assets font), Vietnamese (font_vi_fallback_16)
# and the French extras of font_fr_fallback_16.
FR_EXTRA = set("àâæçéèêëîïôœùûüÿÀÂÆÇÉÈÊËÎÏÔŒÙÛÜŸ«»’“”…€°")


def drawable(ch):
    cp = ord(ch)
    return (0x20 <= cp < 0x7F) or ch in FR_EXTRA or (0xC0 <= cp <= 0xFF) or (0x102 <= cp <= 0x1EF9)


def c_str(text):
    for ch in text:
        if not drawable(ch):
            sys.exit(f"Character {ch!r} (U+{ord(ch):04X}) cannot be drawn: {text!r}")
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    items = lessons.LESSONS
    if len(items) != 36:
        sys.exit(f"Expected 36 lessons, found {len(items)}")
    out = [
        "// Generated by tools/french-course/gen.py from tools/french-course/lessons.py. Do not edit.",
        '#include "french_course.h"',
        "",
        "namespace {",
    ]
    for i, lesson in enumerate(items):
        if lesson["unit"] not in lessons.UNITS:
            sys.exit(f"Lesson {i + 1}: unknown unit {lesson['unit']}")
        if not 1 <= len(lesson["words"]) <= 255 or not lesson["phrases"]:
            sys.exit(f"Lesson {i + 1}: needs words and phrases")
        for name in ("words", "phrases"):
            out.append(f"const FrenchItem k{name.capitalize()}{i + 1}[] = {{")
            for fr, vi in lesson[name]:
                out.append(f"    {{{c_str(fr)}, {c_str(vi)}}},")
            out.append("};")
    out.append("}  // namespace")
    out.append("")
    out.append("const FrenchLesson kFrenchLessons[] = {")
    for i, lesson in enumerate(items):
        n = i + 1
        out.append(
            f"    {{{lesson['unit']}, {c_str(lesson['title'])}, {c_str(lesson['theme'])},\n"
            f"     {c_str(lesson['goals'])},\n"
            f"     {c_str(lesson['grammar'])},\n"
            f"     kWords{n}, {len(lesson['words'])}, kPhrases{n}, {len(lesson['phrases'])}}},"
        )
    out.append("};")
    out.append(f"const int kFrenchLessonCount = {len(items)};")
    out.append("")
    out.append("const char* const kFrenchUnitTitles[] = {")
    out.append('    "",')
    for unit in sorted(lessons.UNITS):
        out.append(f"    {c_str(lessons.UNITS[unit])},")
    out.append("};")
    out.append(f"const int kFrenchUnitCount = {len(lessons.UNITS)};")
    out.append("")
    OUT.write_text("\n".join(out), encoding="utf-8")
    words = sum(len(l["words"]) for l in items)
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(items)} lessons, {words} words")


if __name__ == "__main__":
    main()
