# Converts a few Material Symbols glyphs into an LVGL 9 bitmap font (4 bpp, uncompressed).
import sys
from PIL import Image, ImageDraw, ImageFont
ttf, size, name, out = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4]
cps = sorted(int(x, 16) for x in sys.argv[5].split(','))
font = ImageFont.truetype(ttf, size)
ascent, descent = font.getmetrics()
bitmap = []
dscs = []
for cp in cps:
    ch = chr(cp)
    x0, y0, x1, y1 = font.getbbox(ch, anchor='ls')
    w, h = max(0, x1 - x0), max(0, y1 - y0)
    img = Image.new('L', (max(w, 1), max(h, 1)), 0)
    ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor='ls')
    px = list(img.get_flattened_data()) if hasattr(img, "get_flattened_data") else list(img.getdata())
    start = len(bitmap)
    nib = [p >> 4 for p in px[: w * h]]
    if len(nib) % 2:
        nib.append(0)
    for i in range(0, len(nib), 2):
        bitmap.append((nib[i] << 4) | nib[i + 1])
    adv = round(font.getlength(ch) * 16)
    dscs.append((start, adv, w, h, x0, -y1))
lines = ['/* Material Symbols Rounded (Apache 2.0), %dpx 4bpp: generated by tools/app_icons/mkfont.py */' % size,
         '#include "lvgl.h"', '',
         'static const uint8_t glyph_bitmap[] = {']
for i in range(0, len(bitmap), 16):
    lines.append('    ' + ', '.join('0x%02x' % b for b in bitmap[i:i + 16]) + ',')
lines.append('};')
lines.append('static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {')
lines.append('    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},')
for s, a, w, h, ox, oy in dscs:
    lines.append('    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d},' % (s, a, w, h, ox, oy))
lines.append('};')
lines.append('static const uint16_t unicode_list[] = {' + ', '.join('0x%x' % (c - cps[0]) for c in cps) + '};')
lines.append('static const lv_font_fmt_txt_cmap_t cmaps[] = {')
lines.append('    {.range_start = 0x%x, .range_length = %d, .glyph_id_start = 1, .unicode_list = unicode_list,' % (cps[0], cps[-1] - cps[0] + 1))
lines.append('     .glyph_id_ofs_list = NULL, .list_length = %d, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY},' % len(cps))
lines.append('};')
lines += ['static const lv_font_fmt_txt_dsc_t font_dsc = {',
          '    .glyph_bitmap = glyph_bitmap,', '    .glyph_dsc = glyph_dsc,', '    .cmaps = cmaps,',
          '    .kern_dsc = NULL,', '    .kern_scale = 0,', '    .cmap_num = 1,', '    .bpp = 4,',
          '    .kern_classes = 0,', '    .bitmap_format = 0,', '};',
          'const lv_font_t %s = {' % name,
          '    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,',
          '    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,',
          '    .line_height = %d,' % (ascent + descent), '    .base_line = %d,' % descent,
          '    .subpx = LV_FONT_SUBPX_NONE,', '    .underline_position = 0,', '    .underline_thickness = 0,',
          '    .dsc = &font_dsc,', '};', '']
open(out, 'w').write('\n'.join(lines))
print(len(bitmap), 'bytes of bitmap,', len(cps), 'glyphs')
